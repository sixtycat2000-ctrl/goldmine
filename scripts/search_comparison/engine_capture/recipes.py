TOKENS = {arg[1:-1] for argv in RECIPES.values() for arg in argv if re.fullmatch(r"\{[a-z_]+\}", arg)}
TOKEN = re.compile(r"\{([a-z_]+)\}\Z")
LITERAL_GLOB = "**/*.{md,rst,py,c}"


def compile_recipe(name, values):
    if name not in RECIPES:
        raise EvaluationError("unknown comparison executable recipe", status="MISSING")
    argv = []
    for arg in RECIPES[name]:
        if not isinstance(arg, str) or not arg or "\x00" in arg:
            raise EvaluationError("invalid fixed comparison argument")
        match = TOKEN.fullmatch(arg)
        if match:
            key = match[1]
            if key not in TOKENS or key not in values:
                raise EvaluationError("unresolved/unknown executable placeholder", status="MISSING")
            value = values[key]
            if not isinstance(value, str) or not value or "\x00" in value:
                raise EvaluationError("each token must be one literal nonempty argv item")
            argv.append(value)
        elif ("{" in arg or "}" in arg) and arg != LITERAL_GLOB:
            raise EvaluationError("malformed/embedded executable placeholder")
        else:
            argv.append(arg)
    return argv
