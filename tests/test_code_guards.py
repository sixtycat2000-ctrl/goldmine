"""P2: code-content guards + notebook cell extraction (DigUp CodeExtractor
port). Generated and minified files are honest unsupported rows (QUALITY
refusals); notebooks are read as cells and their outputs (base64 blobs)
never enter the index — previously the raw JSON was chunked as code text.

User decision 2026-10-25: the private-key CONTENT scan is REMOVED — goldmine
is purely local, a key pasted into one's own code file is indexable. The
extension-based is_secret (.pem/.key/.env...) gate is unchanged. The test
below pins that stance so it is not silently re-added.
"""

from __future__ import annotations

import json

import pytest

from goldmine.ingest.rules import code_content_refusal


def test_private_key_content_is_indexed_pure_local():
    """User decision 2026-10-25: goldmine is purely local — a key pasted
    into one's own code file is indexable content, not a refusal. Only the
    extension-based is_secret gate exists (unchanged, tested in test_rules)."""
    text = "notes about deployment\n\n-----BEGIN RSA PRIVATE KEY-----\nMIIE...\n"
    assert code_content_refusal(text) is None


@pytest.mark.parametrize(
    "marker",
    [
        "DO NOT EDIT",
        "@generated",
        "Code generated by",
        "Autogenerated by",
        "Generated by the protocol",
    ],
)
def test_generated_markers_refused_in_head(marker):
    head = f"# {marker} by tool xyz\nrest of file\n"
    assert code_content_refusal(head) == f"made by a program ({marker})"


def test_minified_needs_both_conditions():
    long_line = "x" * 4000
    many_long = "\n".join(["y" * 400] * 5)
    assert code_content_refusal(long_line + "\n" + many_long) == "minified content"
    # avg > 300 but NO single line > 3000 -> not minified (DigUp: AND)
    assert code_content_refusal("\n".join(["y" * 400] * 5)) is None
    # one long line but short average -> not minified
    assert code_content_refusal("short\n" * 50 + "z" * 4000 + "\n") is None


def test_clean_code_passes():
    src = "def retry(fn, attempts=3):\n    for i in range(attempts):\n        return fn()\n"
    assert code_content_refusal(src) is None


def _nb4():
    return {
        "cells": [
            {"cell_type": "markdown", "source": ["# Analysis notes\n", "refund policy"]},
            {
                "cell_type": "code",
                "source": "def load(path):\n    return open(path).read()\n",
                "outputs": [
                    {"data": {"image/png": "iVBORw0KGgo=" * 100}}  # base64 blob
                ],
            },
        ],
        "metadata": {},
        "nbformat": 4,
    }


def _pipeline_outcome(tmp_home, tmp_path, name, content):
    from goldmine.backends.mock import MockBackend
    from goldmine.config import Config
    from goldmine.ingest import IngestPipeline
    from goldmine.store import Store

    cfg = Config()
    cfg.home = tmp_home / "gmhome"
    cfg.backend = "mock"
    root = tmp_path / "tree"
    root.mkdir(exist_ok=True)
    (root / name).write_text(content, encoding="utf-8")
    store = Store(tmp_path / "g.sqlite")
    report = IngestPipeline(cfg, store, MockBackend(dim=768)).run([str(root)], code=True)
    rec = store.find_by_path(str(root / name))
    caps = {
        r[0]: (r[1], r[2])
        for r in store.db.execute("SELECT path, capability, detail FROM files")
    }
    store.close()
    return report, rec, caps


def test_notebook_outputs_never_indexed(tmp_home, tmp_path):
    raw = json.dumps(_nb4())
    report, rec, caps = _pipeline_outcome(tmp_home, tmp_path, "analysis.ipynb", raw)
    assert rec.capability == "content_indexed"
    assert rec.extractor_version == "ipynb-stdlib.v1"
    body = " ".join(
        row[0] or ""
        for row in _fts_bodies(tmp_path / "g.sqlite")
    )
    assert "refund policy" in body and "def load(path):" in body
    assert "iVBORw0KGgo" not in body, "base64 outputs must never enter the index"


def _fts_bodies(db_path):
    from goldmine.store import Store

    store = Store(db_path, ro=True)
    rows = store.db.execute("SELECT body FROM fts").fetchall()
    store.close()
    return rows


def test_notebook_nbformat3_and_malformed(tmp_home, tmp_path):
    nb3 = {"worksheets": [{"cells": [{"input": ["print('hello')\n"]}]}]}
    report, rec, caps = _pipeline_outcome(tmp_home, tmp_path, "old.ipynb", json.dumps(nb3))
    assert rec.capability == "content_indexed"
    assert "print('hello')" in " ".join(r[0] or "" for r in _fts_bodies(tmp_path / "g.sqlite"))

    report, rec, caps = _pipeline_outcome(tmp_home, tmp_path, "broken.ipynb", "{not json")
    assert rec.capability == "failed"
    assert "not a valid notebook" in (rec.detail or "")


def test_private_key_py_is_indexed_pure_local(tmp_home, tmp_path):
    """Same stance end-to-end: a code file containing a key block indexes
    normally (pure local — no content-level key refusal)."""
    report, rec, caps = _pipeline_outcome(
        tmp_home, tmp_path, "leaked.py",
        "-----BEGIN OPENSSH PRIVATE KEY-----\nb3BlbnNzaC1rZXktdjEAAAAA\n",
    )
    assert rec.capability == "content_indexed"


def test_generated_and_minified_py_unsupported(tmp_home, tmp_path):
    report, rec, caps = _pipeline_outcome(
        tmp_home, tmp_path, "bundle.py",
        "// @generated file — do not edit\nvar a=1;\n",
    )
    assert rec.capability == "unsupported"
    assert "made by a program" in (rec.detail or "")

    report, rec, caps = _pipeline_outcome(
        tmp_home, tmp_path, "min.js.py",
        "\n".join(["z" * 500] * 6) + "\n" + "y" * 5000 + "\n",
    )
    assert rec.capability == "unsupported"
    assert rec.detail == "minified content"


def test_clean_py_still_indexes(tmp_home, tmp_path):
    report, rec, caps = _pipeline_outcome(
        tmp_home, tmp_path, "fine.py", "def add(a, b):\n    return a + b\n"
    )
    assert rec.capability == "content_indexed"
